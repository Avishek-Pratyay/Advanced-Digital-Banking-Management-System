import type { Statement, TxnDetail } from "@/types/api";
import { label } from "./constants";
import { formatMoney } from "./money";

const INK: [number, number, number] = [21, 33, 32];
const TEAL: [number, number, number] = [14, 98, 92];
const GOLD: [number, number, number] = [184, 132, 40];
const MUTED: [number, number, number] = [104, 116, 113];

function header(doc: import("jspdf").jsPDF, title: string) {
  doc.setFillColor(10, 35, 35);
  doc.rect(0, 0, 210, 34, "F");
  doc.setFillColor(...GOLD);
  doc.roundedRect(14, 10, 14, 14, 3, 3, "F");
  doc.setDrawColor(10, 35, 35);
  doc.setLineWidth(1.1);
  doc.circle(21, 17, 3.6);
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold").setFontSize(17).text("Vaultline", 33, 18);
  doc.setFont("helvetica", "normal").setFontSize(8).setTextColor(160, 190, 185).text("DIGITAL BANK  ·  SIMULATED", 33, 23.5);
  doc.setFont("helvetica", "bold").setFontSize(12).setTextColor(255, 255, 255).text(title, 196, 19, { align: "right" });
}
function footer(doc: import("jspdf").jsPDF) {
  const h = doc.internal.pageSize.getHeight();
  doc.setDrawColor(229, 225, 214).line(14, h - 18, 196, h - 18);
  doc.setFont("helvetica", "normal").setFontSize(7.5).setTextColor(...MUTED);
  doc.text("This document was generated by a simulated banking system for assessment purposes. No real funds were moved.", 14, h - 12);
}

/** Single-transaction receipt (PDF) with a tamper-evident reference derived from the immutable transaction facts. */
export async function downloadReceipt(t: TxnDetail) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  header(doc, "TRANSACTION RECEIPT");

  doc.setTextColor(...MUTED).setFont("helvetica", "normal").setFontSize(9).text("AMOUNT", 14, 50);
  doc.setTextColor(...INK).setFont("helvetica", "bold").setFontSize(30).text(formatMoney(t.amount), 14, 62);
  const ok = t.status === "COMPLETED";
  if (ok) doc.setFillColor(217, 242, 230);
  else doc.setFillColor(253, 238, 208);
  doc.roundedRect(150, 50, 46, 11, 5.5, 5.5, "F");
  if (ok) doc.setTextColor(20, 128, 88);
  else doc.setTextColor(176, 112, 20);
  doc.setFontSize(10).text(label(t.status).toUpperCase(), 173, 57, { align: "center" });

  const rows: [string, string][] = [
    ["Transaction ID", t.txnId],
    ["Reference code", t.reference],
    ["Type", label(t.type)],
    ["Date & time", new Date(t.createdAt).toLocaleString("en-US", { dateStyle: "long", timeStyle: "short" })],
    ["From", t.sender ? `${t.sender.ownerName}  ·  ${t.sender.accountNumber}` : "—"],
    ["To", t.receiver ? `${t.receiver.ownerName}  ·  ${t.receiver.accountNumber}` : "—"],
    ["Amount", formatMoney(t.amount)],
    ["Fee", formatMoney(t.fee)],
    ["Total debited", t.sender ? formatMoney(t.total) : "—"],
    ["Description", t.description || "—"],
  ];
  let y = 78;
  doc.setDrawColor(229, 225, 214);
  for (const [k, v] of rows) {
    doc.setFont("helvetica", "normal").setFontSize(9.5).setTextColor(...MUTED).text(k, 14, y);
    doc.setFont(k === "Transaction ID" || k === "Reference code" ? "courier" : "helvetica", "bold").setFontSize(10.5).setTextColor(...INK).text(doc.splitTextToSize(v, 110), 196, y, { align: "right" });
    y += 11;
    doc.line(14, y - 6, 196, y - 6);
  }
  doc.setFillColor(222, 240, 236).roundedRect(14, y + 4, 182, 20, 3, 3, "F");
  doc.setTextColor(...TEAL).setFont("helvetica", "bold").setFontSize(9).text("VERIFICATION", 20, y + 12);
  doc.setFont("courier", "bold").setFontSize(13).text(`VL-${t.reference}`, 20, y + 19.5);
  doc.setFont("helvetica", "normal").setFontSize(8).setTextColor(...MUTED).text("Quote this reference when contacting support.", 196, y + 16, { align: "right" });
  footer(doc);
  doc.save(`receipt-${t.txnId}.pdf`);
}

export async function downloadStatementPdf(s: Statement) {
  const { jsPDF } = await import("jspdf");
  const autoTable = (await import("jspdf-autotable")).default;
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  header(doc, "ACCOUNT STATEMENT");
  doc.setTextColor(...INK).setFont("helvetica", "bold").setFontSize(11).text(s.account.owner, 14, 46);
  doc.setFont("helvetica", "normal").setFontSize(9.5).setTextColor(...MUTED);
  doc.text(`${label(s.account.type)} account  ·  ${s.account.accountNumber}`, 14, 52);
  doc.text(`Period: ${s.period.from} to ${s.period.to}`, 14, 58);
  const boxes: [string, string][] = [["Opening", formatMoney(s.openingBalance)], ["Credits", formatMoney(s.totalCredits)], ["Debits", formatMoney(s.totalDebits)], ["Closing", formatMoney(s.closingBalance)]];
  boxes.forEach(([k, v], i) => {
    const x = 14 + i * 46;
    doc.setFillColor(246, 244, 239).roundedRect(x, 64, 43, 17, 2.5, 2.5, "F");
    doc.setFontSize(7.5).setTextColor(...MUTED).setFont("helvetica", "normal").text(k.toUpperCase(), x + 3, 70);
    doc.setFontSize(10.5).setTextColor(...INK).setFont("helvetica", "bold").text(v, x + 3, 77);
  });
  autoTable(doc, {
    startY: 88,
    head: [["Date", "Transaction", "Description", "Debit", "Credit", "Balance"]],
    body: s.entries.map((e) => [new Date(e.date).toLocaleDateString("en-US", { year: "2-digit", month: "short", day: "2-digit" }), e.txnId, e.description || label(e.type), e.debit ? formatMoney(e.debit) : "", e.credit ? formatMoney(e.credit) : "", formatMoney(e.balance)]),
    styles: { fontSize: 8, cellPadding: 2.2, textColor: INK },
    headStyles: { fillColor: TEAL, textColor: 255, fontStyle: "bold" },
    alternateRowStyles: { fillColor: [250, 248, 243] },
    columnStyles: { 3: { halign: "right" }, 4: { halign: "right" }, 5: { halign: "right" } },
    margin: { left: 14, right: 14, bottom: 22 },
    didDrawPage: () => footer(doc),
  });
  doc.save(`statement-${s.account.accountNumber}-${s.period.from}_${s.period.to}.pdf`);
}
